"""Shared data structures and helpers for NetVisBench.

Every benchmark item is generated by code, so its ground-truth answer is
computed (never hand-labelled). Each item also carries a *textual
rendering* of exactly the information shown in the image. This lets us
run the key control experiment: does the model answer better from the
picture or from the same facts written as text?
"""
from __future__ import annotations

import json
import random
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")  # headless rendering
import matplotlib.pyplot as plt  # noqa: E402

DIFFICULTIES = ("easy", "medium", "hard", "expert")
DPI = 110


@dataclass
class Item:
    """One benchmark question."""

    id: str
    family: str          # task family, e.g. "topology"
    subtype: str         # question variant inside the family
    difficulty: str      # easy / medium / hard
    question: str        # question text shown to the model
    answer: str          # canonical ground-truth answer
    answer_type: str     # "int", "choice" or "label"
    image: str           # path of the PNG, relative to the dataset root
    text_rendering: str  # the same facts as the image, written as text
    choices: list[str] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)

    def to_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False)


def save_fig(fig: plt.Figure, out_dir: Path, name: str) -> str:
    """Save a figure as PNG under out_dir/images and return its relative path."""
    img_dir = out_dir / "images"
    img_dir.mkdir(parents=True, exist_ok=True)
    path = img_dir / f"{name}.png"
    fig.savefig(path, dpi=DPI, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return f"images/{name}.png"


def make_rng(seed: int, *parts: Any) -> random.Random:
    """Deterministic RNG derived from a global seed and item-specific parts."""
    key = "|".join(str(p) for p in (seed, *parts))
    return random.Random(key)


def load_items(dataset_dir: str | Path) -> list[Item]:
    path = Path(dataset_dir) / "items.jsonl"
    with open(path, encoding="utf-8") as f:
        return [Item(**json.loads(line)) for line in f if line.strip()]
